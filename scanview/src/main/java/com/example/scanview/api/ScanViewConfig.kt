package com.example.scanview.api

/**
 * Конфигурация библиотеки ScanView.
 * Используется для дипломных экспериментов (изменение глубины, частоты семплирования).
 */
data class ScanViewConfig(
    /**
     * Глубина обхода ViewNode-дерева (1, 2 или 3).
     * Влияет на M4 (объём JSON) и время захвата.
     * Дипломный эксперимент: сравнить depth=1,2,3 по размеру JSON.
     */
    val maxViewNodeDepth: Int = 2,

    /**
     * Максимальное количество промежуточных точек движения (SWIPE).
     * Снижает M4 без потери информации о направлении.
     */
    val maxMoveEventSamples: Int = 8
)
